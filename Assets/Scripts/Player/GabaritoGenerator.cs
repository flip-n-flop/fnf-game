using System.Collections.Generic;
using FlipNflop.Commons.PhaseRules;
using UnityEngine;

/// <summary>
/// Generates the reference corner list (answer key) based on flip-flop output events.
/// The corners come from <see cref="FlipNflop.Commons.PhaseRules.AnswerKeyCorners"/> of the shared library FlipNflopCommons,
/// built from the phase definition of the loaded level and the scene geometry.
/// Interacts with <see cref="LevelJsonLoader"/> to parse signal events and <see cref="LevelManager"/> for level boundaries.
/// </summary>
public class GabaritoGenerator
{
    #region Fields & Properties

    /// <summary>
    /// World Y position corresponding to logical LOW state (0).
    /// </summary>
    public readonly float LowY;

    /// <summary>
    /// World Y position corresponding to logical HIGH state (1).
    /// </summary>
    public readonly float HighY;

    /// <summary>
    /// Corner tolerance stored in the geometry of <see cref="AnswerKeyCorners"/>, used by the evaluations of the trace.
    /// </summary>
    private readonly float cornerTolerance;

    /// <summary>
    /// Phase definition of the loaded level, read from <see cref="LevelJsonLoader.CreatePhaseDefinition"/>.
    /// </summary>
    private PhaseDefinition phase;

    /// <summary>
    /// World X where tile 0 of the diagram starts (<see cref="LevelJsonLoader.StartX"/>).
    /// </summary>
    private float diagramOriginX = PhaseGeometry.DefaultDiagramOriginX;

    /// <summary>
    /// List of reference corners generated by the last successful call to <see cref="Generate"/> or <see cref="BuildFromEvents"/>.
    /// Guaranteed not to be null after instantiation.
    /// </summary>
    public List<Vector3> CorrectCorners { get; private set; } = new();

    /// <summary>
    /// Commons answer key corners behind <see cref="CorrectCorners"/>, with the phase and the geometry
    /// (play area start, diagram origin, LOW and HIGH levels, tolerance and slack) used by
    /// <see cref="PathChecker"/>, <see cref="PathVerifier"/> and <see cref="ColumnEvaluator"/>.
    /// Null until a phase is loaded.
    /// </summary>
    public AnswerKeyCorners AnswerKeyCorners { get; private set; }

    #endregion

    #region Constructors

    /// <summary>
    /// Initializes a new instance of the <see cref="GabaritoGenerator"/> class with defined Y bounds for LOW and HIGH logic states
    /// and the default corner tolerance of the shared rules (<see cref="PhaseGeometry.DefaultTolerance"/>).
    /// </summary>
    /// <param name="lowY">World Y position for logical LOW (0).</param>
    /// <param name="highY">World Y position for logical HIGH (1).</param>
    public GabaritoGenerator(float lowY, float highY)
        : this(lowY, highY, PhaseGeometry.DefaultTolerance)
    {
    }

    /// <summary>
    /// Initializes a new instance of the <see cref="GabaritoGenerator"/> class with defined Y bounds for LOW and HIGH logic states
    /// and the corner tolerance that the evaluations of the trace use (the <c>cornerTolerance</c> of <see cref="PathVerifier"/>).
    /// </summary>
    /// <param name="lowY">World Y position for logical LOW (0).</param>
    /// <param name="highY">World Y position for logical HIGH (1).</param>
    /// <param name="cornerTolerance">Maximum distance tolerance for hitting corners, in world units.</param>
    public GabaritoGenerator(float lowY, float highY, float cornerTolerance)
    {
        LowY = lowY;
        HighY = highY;
        this.cornerTolerance = cornerTolerance;
    }

    #endregion

    #region Public Methods

    /// <summary>
    /// Finds the <see cref="LevelJsonLoader"/> in the scene and generates the reference path corners.
    /// Typically invoked once during initialization from <see cref="PathVerifier"/>.
    /// </summary>
    public void Generate()
    {
        var loader = Object.FindAnyObjectByType<LevelJsonLoader>();
        if (loader == null)
        {
            Debug.LogError("[GabaritoGenerator] LevelJsonLoader not found in scene.");
            ClearCorners();
            return;
        }

        LoadPhase(loader);
        var events = loader.ComputeOutputEventsFromParsedSignals();
        BuildFromEvents(events, initialX: 0f, initialState: false);
    }

    /// <summary>
    /// Reconstructs the reference corners for the loaded level with <see cref="FlipNflop.Commons.PhaseRules.AnswerKeyCorners"/>
    /// of the shared library: the first corner at <paramref name="initialX"/> (the start of the playable area), the changes of Q
    /// shifted by the diagram origin, and the last corner at <see cref="LevelManager.phaseEndX"/> (diagram end plus <see cref="LevelManager.phaseSlackTiles"/>).
    /// The shared rules derive the changes of Q from the phase definition of the loaded level, read from <see cref="LevelJsonLoader"/>,
    /// with Q starting at LOW: <paramref name="events"/> must be the output events of that level (as
    /// <see cref="LevelJsonLoader.ComputeOutputEventsFromParsedSignals"/> returns them) and <paramref name="initialState"/> must be false.
    /// Other events, or a HIGH initial state, are reported with an error log and do not change the corners.
    /// Interacts with <see cref="LevelManager"/> to query the slack after the diagram.
    /// </summary>
    /// <param name="events">List of signal transition events containing X coordinate and logical output value.</param>
    /// <param name="initialX">Starting X world coordinate of the path (defaults to 0).</param>
    /// <param name="initialState">Initial logical output state (false = LOW, true = HIGH).</param>
    public void BuildFromEvents(
        List<PathVerifier.SignalEvent> events,
        float initialX = 0f,
        bool initialState = false)
    {
        if (phase == null)
        {
            var loader = Object.FindAnyObjectByType<LevelJsonLoader>();
            if (loader != null) LoadPhase(loader);
        }

        if (phase == null)
        {
            Debug.LogError("[GabaritoGenerator] No level phase definition is available to build the answer key corners.");
            ClearCorners();
            return;
        }

        float slackColumns = LevelManager.Instance != null
            ? LevelManager.Instance.phaseSlackTiles
            : PhaseGeometry.DefaultSlackColumns;
        var geometry = new PhaseGeometry(initialX, diagramOriginX, LowY, HighY, cornerTolerance, slackColumns);

        AnswerKeyCorners = new AnswerKeyCorners(new PhaseAnswerKey(phase), geometry);
        CorrectCorners = AnswerKeyCorners.Corners.ToVector3List();

        if (initialState || !MatchesLevelEvents(events))
        {
            Debug.LogError("[GabaritoGenerator] The given events or initial state differ from the loaded level; " +
                           "the answer key corners follow the level phase definition.");
        }
    }

    #endregion

    #region Private Methods

    /// <summary>
    /// Reads the phase definition and the diagram origin of the loaded level.
    /// Interacts with <see cref="LevelJsonLoader.CreatePhaseDefinition"/> and <see cref="LevelJsonLoader.StartX"/>.
    /// </summary>
    /// <param name="loader">Level loader of the scene.</param>
    private void LoadPhase(LevelJsonLoader loader)
    {
        phase = loader.CreatePhaseDefinition();
        diagramOriginX = loader.StartX;
    }

    /// <summary>
    /// Clears the corners when no level phase is available.
    /// </summary>
    private void ClearCorners()
    {
        CorrectCorners = new List<Vector3>();
        AnswerKeyCorners = null;
    }

    /// <summary>
    /// Checks whether the given events are the output events of the loaded level, shifted by the diagram origin,
    /// as the shared simulation of <see cref="AnswerKeyCorners"/> produces them.
    /// </summary>
    /// <param name="events">Events given to <see cref="BuildFromEvents"/>.</param>
    /// <returns>True when they have the same positions and values, in increasing X.</returns>
    private bool MatchesLevelEvents(List<PathVerifier.SignalEvent> events)
    {
        IReadOnlyList<OutputEvent> expected = AnswerKeyCorners.AnswerKey.Simulation.Events;
        int count = events?.Count ?? 0;
        if (count != expected.Count) return false;
        if (count == 0) return true;

        var sorted = new List<PathVerifier.SignalEvent>(events);
        sorted.Sort((a, b) => a.x.CompareTo(b.x));

        for (int i = 0; i < count; i++)
        {
            if (sorted[i].x != diagramOriginX + expected[i].X || sorted[i].value != expected[i].Value)
                return false;
        }

        return true;
    }

    #endregion
}
